#include <iostream>
#include <clocale>
#include <iomanip>
#include <string>
using namespace std;

int main() {
    setlocale(LC_ALL, ".UTF8");

// ПЕРВОЕ ЗАДАНИЕ
    
    cout << "ПЕРВОЕ ЗАДАНИЕ" << endl;

    int N = 100;
    int a[N] = {};

    int k = 0;
    cout << "Введите длину массива: ";
    cin >> k;

    if(k > N || k == 0){
        cout << "Некорректная длина массива";
        return 1;
    }

    cout << "Введите " << k << " элементов массива: ";

    for(int i = 0; i < k; i++){
        cin >> a[i];
    }

    int cur, step, end;
    string way;

    cout << "Введите индекс стартового элемента (от 0 до " << k - 1 << "): ";
    cin >> cur;

    if(cur < 0 || cur > k - 1){
        cout << "Индекс выходит за пределы кольца";
        return 1;
    }

    cout << "Введите шаг: ";
    cin >> step;

    cout << "Введите направление шага (вправо - r / влево - l): ";
    cin >> way;

    if(way == "r"){
        end = (cur + step) % k;
    }

    else if(way == "l"){
        end = (cur - (step % k) + k) % k;
    }

    else{
        cout << "Направление выбрано некорректно";
        return 1;
    }

    cout << "Полученный элемент: " << a[end] << endl << endl;

// ВТОРОЕ ЗАДАНИЕ

    cout << "ВТОРОЕ ЗАДАНИЕ" << endl;

    int K;
    cout << "Введите индекс K-ого элемента от 0 до " << k - 1 << ": ";
    cin >> K;

    if(K < 0 || K > k - 1){
        cout << "Индекс выходит за пределы кольца";
        return 1;
    }
    
    cout << "Вывод элементов от K-ого до K - 1 - ого элементов: ";
    for(int i = 0; i < k; i++){
        cout << a[K] << " ";
        K--;
        if(K < 0){
            K = k - 1; // Переход к от первого элемента кольца к последнему 
        }
    }

    cout << endl << endl;

// ТРЕТЬЕ ЗАДАНИЕ

    cout << "ТРЕТЬЕ ЗАДАНИЕ";

    int max = a[0]; // Пусть изначально максимальный элемент кольца - первый
    for(int i = 0; i < k; i++){
        if(a[i] > max){
            max = a[i];
        }
    }

    cout << endl;
    cout << "Максимальный элемент кольца: " << max << endl;

    int new_ind = 0; // Переменная для накопления длины кольца без элементов с максимальным значением
    // Удаляем из кольца все элементы, равные максимальному значению 
    for(int i = 0; i < k; i++){
        if(a[i] != max){
            a[new_ind] = a[i];
            new_ind++;
        }
    }

    k = new_ind; // Новая длина кольца без элементов с максимальным значением

    cout << "Кольцо без элементов с максимальным значением: ";
    for(int i = 0; i < k; i++){
        cout << a[i] << " ";
    }

    cout << endl << endl;
    
// ЧЕТВЁРТОЕ ЗАДАНИЕ
    cout << "ЧЕТВЁРТОЕ ЗАДАНИЕ" << endl;

    if(k == 0){
        cout << "Кольцо пустое";
        return 0;
    }

    cout << "Введите индекс K-ого элемента от 0 до " << k - 1 << ": ";
    cin >> K;

    if(K < 0 || K > k - 1){
        cout << "Индекс выходит за пределы кольца";
        return 1;
    }
    
    cout << "Вывод элементов от K-ого до K + 1 - ого элементов: ";
    for(int i = 0; i < k; i++){
        cout << a[K] << " ";
        K++;
        if(K > k - 1){
            K = 0; // Переход к от последнего элемента кольца к первому 
        }
    }

    return 0;
}




